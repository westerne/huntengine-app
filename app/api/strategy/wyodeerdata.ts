// ─────────────────────────────────────────────────────────────────────────────
// WYOMING DEER DATA — V2 (split product-type architecture)
//
// Each record = ONE HUNT PRODUCT (not one geographic unit).
//   - GENERAL_REGION: a general region tag. Has its own draw data.
//   - UNIT_IN_REGION: one geographic unit hunted under a General Region tag.
//                    No own draw data — references parentRegion.
//   - LIMITED_QUOTA: a standalone antlered mule deer limited quota tag.
//   - LIMITED_QUOTA_WHITETAIL: a Type 3 any-whitetail tag.
//
// Key format: no padding. Examples: "G", "135-GEN", "128-1", "11-12-13-14-3".
//
// Data provenance:
//   - Draw history (quotas, min points, odds): WGFD Demand Reports.
//   - Season dates: WGFD Ch. 6 regulations (April 2024).
//   - Parent region mapping: Ch. 6 Section 6 (authoritative).
//   - Trophy typical / topEnd for FULL entries: sourced per field notes in V1.
//   - Trophy data for NEEDS_TROPHY_DATA entries: aggregated table data where
//     available, conservative geographic estimates otherwise.
//   - publicPct / wildernessPct / buckPerHundredDoe: aggregated table data.
//     Applied at unit level following Ch. 6 region assignments.
// ─────────────────────────────────────────────────────────────────────────────

export type ProductType =
  | "GENERAL_REGION"
  | "UNIT_IN_REGION"
  | "LIMITED_QUOTA"
  | "LIMITED_QUOTA_WHITETAIL";

export type DataCompleteness =
  | "FULL"
  | "NEEDS_TROPHY_DATA"
  | "NEEDS_FIELD_DATA";

export type DrawYearData = {
  year: number;
  nr_regular: { quota: number; minPoints: number | null; oddsAtMin: string | null; notes?: string };
  nr_special: { quota: number; minPoints: number | null; oddsAtMin: string | null; notes?: string };
  nr_random: { quota: number; firstChoiceApplicants: number; approxOdds: string | null };
  nr_special_random: { quota: number; firstChoiceApplicants: number; approxOdds: string | null };
  resident: { quota: number; firstChoiceApplicants: number; approxOdds: string | null };
};

export type Seasons = {
  archery?: { open: string; close: string; notes?: string };
  rifle?: { open: string; close: string; notes?: string };
  muzzleloader?: { open: string; close: string; notes?: string };
};

