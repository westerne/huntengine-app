// ─────────────────────────────────────────────────────────────────────────────
// HELPER: DRAW TREND ANALYSIS PROMPT BLOCK
// Pass this to the AI when asking for trend analysis on a specific unit.
// For UNIT_IN_REGION entries, pass the parent region entry instead.
// ─────────────────────────────────────────────────────────────────────────────
export function buildDrawTrendBlock(unit: WyomingDeerUnit, unitName: string, residency: string): string {
  const isResident = residency.toLowerCase().includes('resident');
  let block = `DRAW HISTORY FOR ${unitName}:\n`;

  if (unit.drawHistory.length === 0) {
    return block + `\nNo draw history available. Data status: ${unit.dataCompleteness}.\n`;
  }

  // Sort by year descending so latest is always first
  const sortedHistory = [...unit.drawHistory].sort((a, b) => b.year - a.year);

  for (const year of sortedHistory) {
    block += `\n--- ${year.year} ---\n`;
    if (isResident) {
      block += `RESIDENT: Quota=${year.resident.quota}, First-Choice Applicants=${year.resident.firstChoiceApplicants}, Odds=${year.resident.approxOdds ?? 'N/A'}\n`;
    } else {
      block += `NR REGULAR: Quota=${year.nr_regular.quota}, Min Points=${year.nr_regular.minPoints ?? 'N/A'}, Odds at Min=${year.nr_regular.oddsAtMin ?? 'N/A'}${year.nr_regular.notes ? ' | ' + year.nr_regular.notes : ''}\n`;
      block += `NR SPECIAL: Quota=${year.nr_special.quota}, Min Points=${year.nr_special.minPoints ?? 'N/A'}, Odds at Min=${year.nr_special.oddsAtMin ?? 'N/A'}\n`;
      block += `NR RANDOM: Quota=${year.nr_random.quota}, First-Choice Applicants=${year.nr_random.firstChoiceApplicants}, Odds=${year.nr_random.approxOdds ?? 'N/A'}\n`;
      block += `NR SPECIAL RANDOM: Quota=${year.nr_special_random.quota}, First-Choice Applicants=${year.nr_special_random.firstChoiceApplicants}, Odds=${year.nr_special_random.approxOdds ?? 'N/A'}\n`;
    }
  }

  block += `\nBASED ON THIS TREND, provide a brief prediction for the 2026 draw cycle. Note any trend in minimum points required, quota changes, or applicant pressure changes. Keep to 2-3 sentences.\n`;
  return block;
}

// ─────────────────────────────────────────────────────────────────────────────
// HELPER: RESOLVE DRAW DATA
// For UNIT_IN_REGION entries, returns the parent region's draw data.
// For GENERAL_REGION or LIMITED_QUOTA entries, returns its own.
// ─────────────────────────────────────────────────────────────────────────────
export function resolveDrawData(unit: WyomingDeerUnit): DrawYearData[] {
  if (unit.productType === "UNIT_IN_REGION" && unit.parentRegion) {
    const parent = WYOMING_DEER_UNITS[unit.parentRegion];
    return parent ? parent.drawHistory : [];
  }
  return unit.drawHistory;
}